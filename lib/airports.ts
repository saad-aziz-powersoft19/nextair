export function getAllCountries(): string[] {
  const set = new Set<string>();
  AIRPORTS.forEach((a) => set.add(a.country));
  return Array.from(set).sort();
}

export function getAirportsByCountry(country: string): Airport[] {
  return AIRPORTS.filter((a) => a.country.toLowerCase() === country.toLowerCase());
}

export function getAirportByCode(code: string): Airport | undefined {
  const upper = code.toUpperCase();
  return AIRPORTS.find((a) => a.code === upper || a.icao === upper);
}

export function searchAirports(query: string): Airport[] {
  if (!query.trim()) return AIRPORTS;
  const q = query.toLowerCase().trim();
  return AIRPORTS.filter(
    (a) =>
      a.code.toLowerCase().includes(q) ||
      a.icao.toLowerCase().includes(q) ||
      a.city.toLowerCase().includes(q) ||
      a.name.toLowerCase().includes(q) ||
      a.country.toLowerCase().includes(q)
  );
}

